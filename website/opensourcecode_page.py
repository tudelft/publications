# Write opensourcecode.html: the open-source code page of https://mavlab.tudelft.nl,
# made from ../opensourcecode.json
#
# The page is an HTML fragment that WordPress loads from GitHub (see
# wordpress/mavlab_github_include.php). Papers are teachPress [tpsingle key=...]
# shortcodes, so they look like on the rest of the website; WordPress expands them.
# The titles of the website posts come from the public WordPress REST API; when it does
# not answer, opensourcecode.html is not changed and the exit code is 1.
import html
import json
import os
import sys
from collections import OrderedDict

import requests

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, '..', 'opensourcecode.json')
OUTPUT = os.path.join(HERE, 'opensourcecode.html')
WP = 'https://mavlab.tudelft.nl/wp-json/wp/v2/'
TPSINGLE = '[tpsingle author_name="simple" show_bibtex=0 headline=0 template="tp_template_orig_s" link_style="direct" key="%s" link=true]'


def post_title(url):
    slug = url.rstrip('/').rsplit('/', 1)[-1]
    for kind in ('posts', 'pages'):
        p = requests.get(WP + kind, params={'slug': slug, '_fields': 'title'}, timeout=60)
        p.raise_for_status()
        if p.json():
            return html.unescape(p.json()[0]['title']['rendered'])
    return None


def repo_label(url):
    return url.split('://', 1)[-1].removeprefix('www.').removesuffix('.git')


def main():
    code = json.load(open(JSON, encoding='utf-8'))
    titles = {}
    try:
        for url in sorted({p for c in code for p in c['posts']}):
            titles[url] = post_title(url)
    except requests.RequestException as e:
        print('The website does not answer (%s): %s not changed.' % (e, OUTPUT))
        return False
    missing = [u for u, t in titles.items() if not t]
    if missing:
        print('Not on the website any more:', ' '.join(missing))

    years = OrderedDict()
    for c in code:
        years.setdefault(c['year'], []).append(c)

    e = html.escape
    out = ['<!-- AUTOGENERATED by website/opensourcecode_page.py from opensourcecode.json -->',
           '<div class="mavlab-code-list">']
    for year, items in years.items():
        out.append('<h3 class="mavlab-code-year">%d</h3>' % year)
        for c in items:
            out.append('<div class="mavlab-code">')
            out.append('<p class="mavlab-code-name"><a href="%s" target="_blank" rel="noopener">%s</a> <span class="mavlab-code-repo">%s</span></p>'
                       % (e(c['repo']), e(c['name']), e(repo_label(c['repo']))))
            if c['papers']:
                out.append('<div class="mavlab-code-papers">')
                out += [TPSINGLE % e(k) for k in c['papers']]
                out.append('</div>')
            posts = [(u, titles.get(u)) for u in c['posts'] if titles.get(u)]
            if posts:
                out.append('<p class="mavlab-code-posts">On this website: %s</p>'
                           % ', '.join('<a href="%s">%s</a>' % (e(u), e(t)) for u, t in posts))
            out.append('</div>')
    out.append('</div>')

    with open(OUTPUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(len(code), 'code entries written to', OUTPUT)
    return not missing


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
