# Download the arXiv preprints of MAVLab staff into arxiv.bib
#
# Uses the official arXiv API (https://info.arxiv.org/help/api/), which returns
# the metadata of many papers per request, instead of one arxiv2bibtex.org
# request per paper (that site stops answering after about 50 requests, #102).
#
# When the API does not answer, the previous version of the affected entries is
# kept, and when a search fails no papers are removed. The summary lists what
# changed and what failed; run the script again later to retry.
import codecs
import os
import re
import time
import xml.etree.ElementTree as ET

import requests


SEARCH = ['guido de croon', 'christophe de wagter', 'ewoud smeur', 'sjoerd tijmons', 'salua hamaza', 'marija popovic']
API_URL = 'https://export.arxiv.org/api/query'
ABS_URL = 'https://arxiv.org/abs/'

PAUSE = 3           # seconds between API requests (arXiv asks for at least 3)
RETRIES = 4         # attempts per request, pausing RETRY_PAUSE * attempt seconds in between
RETRY_PAUSE = 30
BATCH = 50          # papers per API request

NS = {'atom': 'http://www.w3.org/2005/Atom', 'arxiv': 'http://arxiv.org/schemas/atom'}

# '# <code>: <url>' starts the block of every entry (old files used arxiv2bibtex.org urls)
BLOCK = re.compile(r'^# (\S+): https://(?:arxiv\.org/abs/|arxiv2bibtex\.org/)\S*$')


def read_previous(filename):
    entries = {}
    if not os.path.exists(filename):
        return entries
    code = None
    with open(filename, encoding='utf-8-sig') as f:
        for line in f.read().splitlines():
            m = BLOCK.match(line)
            if m:
                code = m.group(1)
                entries[code] = []
            elif code is not None:
                entries[code].append(line)
    return {code: '\n'.join(lines).strip() for code, lines in entries.items()}


def failed_entry(code):
    return '# Error: could not find bibtex for ' + code


def is_failed(bib):
    return bib is None or bib.startswith('# Error')


def write(filename, header, codes, entries):
    # write to a temporary file first, so an interrupted run never leaves a broken arxiv.bib
    tmp = filename + '.tmp'
    bibf = codecs.open(tmp, 'w', 'utf-8')
    bibf.write(u'﻿')
    bibf.write('\n'.join(header) + '\n')
    for code in codes:
        bibf.write('# ' + code + ': ' + ABS_URL + code + '\n\n')
        bibf.write(entries.get(code, failed_entry(code)) + '\n\n\n')
    bibf.close()
    os.replace(tmp, filename)


def query(params):
    # returns the list of <entry> elements, or None when the API keeps failing
    for attempt in range(1, RETRIES + 1):
        time.sleep(PAUSE)
        try:
            p = requests.get(API_URL, params=params, timeout=60)
            if p.status_code == 200:
                entries = ET.fromstring(p.content).findall('atom:entry', NS)
                # the API sometimes answers with an empty feed when it is busy
                if entries:
                    return entries
            print('  empty answer (HTTP', p.status_code, ')')
        except (requests.RequestException, ET.ParseError) as e:
            print('  error:', e)
        if attempt < RETRIES:
            print('  attempt', attempt, 'failed, pausing', RETRY_PAUSE * attempt, 's')
            time.sleep(RETRY_PAUSE * attempt)
    return None


def text(entry, tag):
    e = entry.find(tag, NS)
    return ' '.join(e.text.split()) if e is not None and e.text else ''


def arxiv_code(entry):
    # http://arxiv.org/abs/2304.08802v1 -> 2304.08802
    return re.sub(r'v\d+$', '', text(entry, 'atom:id').split('/abs/')[-1])


def to_bibtex(entry):
    # same format as arxiv2bibtex.org: @article once a journal reference or DOI is known
    code = arxiv_code(entry)
    journal = text(entry, 'arxiv:journal_ref')
    doi = text(entry, 'arxiv:doi')
    authors = ' and '.join(text(a, 'atom:name') for a in entry.findall('atom:author', NS))

    bib = '@' + ('article' if journal or doi else 'misc') + '{' + code + ',\n'
    bib += '\tauthor = {' + authors + '},\n'
    bib += '\ttitle = {' + text(entry, 'atom:title') + '},\n'
    bib += '\tyear = {' + text(entry, 'atom:published')[:4] + '},\n'
    bib += '\teprint = {arXiv:' + code + '},\n'
    if journal:
        bib += '\thowpublished = {' + journal + '},\n'
    if doi:
        bib += '\tdoi = {' + doi + '},\n'
    bib += '\turl = {' + ABS_URL + code + '},\n'
    bib += '\tpdf = {https://arxiv.org/pdf/' + code + '.pdf},\n'
    bib += '}'
    return bib


def import_arxiv(filename):
    previous = read_previous(filename)
    print('Previous', filename, 'has', len(previous), 'entries')

    # Find the papers of every person
    header = ['# AUTOGENERATED']
    codes = []
    for person in SEARCH:
        print('- Search', person)
        header.append('# Import from: ' + API_URL + '?search_query=au:"' + person + '"')
        found = query({'search_query': 'au:"' + person + '"', 'max_results': 500,
                       'sortBy': 'submittedDate', 'sortOrder': 'descending'})
        if found is None:
            print('  no answer, keeping the previously found papers')
            header.append('# Search failed')
            continue
        for code in [arxiv_code(e) for e in found]:
            header.append('# - ' + code)
            if not code in codes:
                codes.append(code)

    # Never drop a paper because a search failed
    removed = [code for code in previous if not code in codes]
    if '# Search failed' in header:
        codes += removed
        removed = []

    # Download the metadata of all papers
    entries = {}
    for i in range(0, len(codes), BATCH):
        batch = codes[i:i + BATCH]
        print('- Download', i + 1, '-', i + len(batch), 'of', len(codes))
        found = query({'id_list': ','.join(batch), 'max_results': len(batch)})
        for e in found or []:
            if arxiv_code(e) in batch and e.find('atom:title', NS) is not None:
                entries[arxiv_code(e)] = to_bibtex(e)

    report = {'new': [], 'updated': [], 'unchanged': [], 'kept previous version': [], 'failed': [], 'removed': removed}
    for code in codes:
        old = previous.get(code)
        if code in entries:
            if is_failed(old):
                report['new'].append(code)
            elif old != entries[code]:
                report['updated'].append(code)
            else:
                report['unchanged'].append(code)
        elif not is_failed(old):
            entries[code] = old
            report['kept previous version'].append(code)
        else:
            report['failed'].append(code)

    write(filename, header, codes, entries)

    print('================================================================')
    print('Summary:', ', '.join('%d %s' % (len(v), k) for k, v in report.items()))
    for k in ['new', 'updated', 'kept previous version', 'failed', 'removed']:
        if report[k]:
            print(' -', k + ':', ' '.join(report[k]))
    if report['kept previous version'] or report['failed'] or '# Search failed' in header:
        print('Not everything could be downloaded: run the script again later.')
    else:
        print('All', len(codes), 'entries are up to date.')


if __name__ == '__main__':
    import_arxiv('arxiv.bib')
